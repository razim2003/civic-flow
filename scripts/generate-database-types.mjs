// Generate from the actual local migrations, never from the hosted project.
import { writeFile } from 'node:fs/promises'
import { createTestDatabase } from '../supabase/tests/harness.ts'

const db = await createTestDatabase()
try {
  const enumRows = (await db.query(`select t.typname name, array_agg(e.enumlabel order by e.enumsortorder) labels from pg_type t join pg_enum e on e.enumtypid=t.oid join pg_namespace n on n.oid=t.typnamespace where n.nspname='public' group by t.typname order by t.typname`)).rows
  const enums = new Map(enumRows.map((row) => [row.name, row.labels]))
  function type(name) {
    if (enums.has(name)) return `Database['public']['Enums']['${name}']`
    if (['int2','int4','int8','float4','float8','numeric','smallint','integer','bigint','double precision'].includes(name)) return 'number'
    if (name === 'bool' || name === 'boolean') return 'boolean'
    if (name === 'jsonb' || name === 'json') return 'Json'
    return 'string'
  }
  const columns = (await db.query(`select c.relname table_name,a.attname column_name,t.typname type_name,a.attnotnull not_null from pg_class c join pg_namespace n on n.oid=c.relnamespace join pg_attribute a on a.attrelid=c.oid join pg_type t on t.oid=a.atttypid where n.nspname='public' and c.relkind='r' and a.attnum>0 and not a.attisdropped order by c.relname,a.attnum`)).rows
  const tables = [...new Set(columns.map((row) => row.table_name))]
  const functions = (await db.query(`select p.proname name,p.proargnames names,p.proargtypes::oid[]::regtype[]::text[] types,t.typname returns from pg_proc p join pg_namespace n on n.oid=p.pronamespace join pg_type t on t.oid=p.prorettype where n.nspname='public' and (t.typname in (select tablename from pg_tables where schemaname='public') or t.typname='jsonb') order by p.proname`)).rows
  let output = '// Generated by npm run db:types from version-controlled SQL. Do not edit.\n'
  output += 'export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]\n\nexport type Database = { public: {\n  Tables: {\n'
  for (const table of tables) {
    output += `    ${table}: {\n      Row: {\n`
    for (const column of columns.filter((row) => row.table_name === table)) output += `        ${column.column_name}: ${type(column.type_name)}${column.not_null ? '' : ' | null'}\n`
    output += '      }\n      Insert: never\n      Update: never\n      Relationships: []\n    }\n'
  }
  output += '  }\n  Views: { [_ in never]: never }\n  Functions: {\n'
  for (const fn of functions) {
    output += `    ${fn.name}: { Args: {\n`
    for (const [i, name] of fn.names.entries()) {
      const pgType = fn.types[i].replace('public.', '')
      output += `      ${name}: ${type(pgType)}${fn.name === 'admin_update_user' && name === 'p_department_id' ? ' | null' : ''}\n`
    }
    output += fn.returns === 'jsonb' ? '    }; Returns: Json }\n' : `    }; Returns: Database['public']['Tables']['${fn.returns}']['Row'][] }\n`
  }
  output += '  }\n  Enums: {\n'
  for (const [name, labels] of enums) output += `    ${name}: ${labels.map((label) => `'${label}'`).join(' | ')}\n`
  output += '  }\n  CompositeTypes: { [_ in never]: never }\n} }\n'
  await writeFile(new URL('../src/shared/lib/supabase/database.types.ts', import.meta.url), output)
  console.log(`Generated database types from ${tables.length} migrated tables and ${functions.length} public RPCs.`)
} finally { await db.close() }
